export function detectInitialLocale(): Locale {
  const stored = window.localStorage.getItem("readwisehub_locale");
  if (stored === "de" || stored === "en") {
    return stored;
  }

  return navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
}
